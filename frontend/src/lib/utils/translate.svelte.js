// Precomputed ultra-fast O(1) hash maps across all languages
export const fastMaps = {
  en: new Map(),
  ta: new Map(),
  hi: new Map(),
  te: new Map(),
  ml: new Map(),
  kn: new Map()
};

function buildFastMaps() {
  const languages = ['ta', 'hi', 'te', 'ml', 'kn'];
  const enDict = UI_DICTIONARY.en || {};

  // Build English map
  for (const [key, val] of Object.entries(enDict)) {
    fastMaps.en.set(key, val);
    fastMaps.en.set(key.toLowerCase(), val);
    if (typeof val === 'string') {
      fastMaps.en.set(val, val);
      fastMaps.en.set(val.toLowerCase(), val);
    }
  }

  for (const lang of languages) {
    const map = fastMaps[lang];
    const dict = UI_DICTIONARY[lang] || {};
    const compDict = COMPANY_DICTIONARY[lang] || {};

    // 1. Direct keys from language dictionary
    for (const [key, val] of Object.entries(dict)) {
      map.set(key, val);
      map.set(key.toLowerCase(), val);
    }

    // 2. English reverse lookups (English key or English string value -> translated value)
    for (const [key, enVal] of Object.entries(enDict)) {
      const translated = dict[key];
      if (translated) {
        map.set(key, translated);
        map.set(key.toLowerCase(), translated);
        if (typeof enVal === 'string') {
          map.set(enVal, translated);
          map.set(enVal.toLowerCase(), translated);
        }
      }
    }

    // 3. Company names
    for (const [comp, compTrans] of Object.entries(compDict)) {
      map.set(comp, compTrans);
      map.set(comp.toLowerCase(), compTrans);
    }
  }
}

buildFastMaps();

export function translateCompanyName(name, langOverride = null) {
  if (!name) return "";
  const lang = langOverride || translationState.currentLang;
  if (lang === 'en') return name;
  const map = fastMaps[lang];
  if (map && map.has(name)) return map.get(name);
  if (map && map.has(name.toLowerCase())) return map.get(name.toLowerCase());
  return name;
}

// Ultra-fast, zero-lag O(1) translation helper without any reactive state churn
export function t(key, langOverride = null) {
  if (!key && key !== 0) return "";
  const strKey = String(key).trim();
  const activeLang = langOverride || translationState.currentLang;

  // English requested
  if (activeLang === 'en') {
    const enMap = fastMaps.en;
    if (enMap.has(strKey)) return enMap.get(strKey);
    return strKey;
  }

  const map = fastMaps[activeLang];
  if (!map) return strKey;

  // 1. Instant O(1) exact match
  if (map.has(strKey)) return map.get(strKey);

  // 2. Instant O(1) lowercase match
  const lowerKey = strKey.toLowerCase();
  if (map.has(lowerKey)) return map.get(lowerKey);

  return strKey;
}

// Safe async translator for dynamic external content if explicitly needed
const translationCache = new Map();
export async function translateDynamic(text, targetLang) {
  if (!targetLang || targetLang === 'en' || !text) return text;
  const cacheKey = `${targetLang}_${text}`;
  if (translationCache.has(cacheKey)) return translationCache.get(cacheKey);

  try {
    const res = await aiService.translateUI(text, targetLang);
    translationCache.set(cacheKey, res);
    return res;
  } catch (e) {
    return text;
  }
}

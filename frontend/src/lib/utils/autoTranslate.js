/**
 * Intelligent single-text or sentence translator with multi-tiered resolution
 */
export function translateText(rawText, targetLang) {
  if (!rawText || targetLang === 'en') return rawText;

  const text = rawText.trim();
  if (!text) return rawText;

  // Skip pure numbers, punctuation, file extensions or URLs
  if (/^[\d\s.,:;!?%/\-+—()#@&*]+$/.test(text) || text.startsWith('http') || text.endsWith('.json') || text.endsWith('.pdf')) {
    return rawText;
  }

  // 1. Instant O(1) Phrase Dictionary lookup
  const phraseMap = fastPhraseMaps[targetLang];
  if (phraseMap) {
    if (phraseMap.has(text)) return rawText.replace(text, phraseMap.get(text));
    const lower = text.toLowerCase();
    if (phraseMap.has(lower)) return rawText.replace(text, phraseMap.get(lower));
  }

  // 2. Instant O(1) Fast UI & Company Maps lookup
  const map = fastMaps[targetLang];
  if (map) {
    if (map.has(text)) return rawText.replace(text, map.get(text));
    const lower = text.toLowerCase();
    if (map.has(lower)) return rawText.replace(text, map.get(lower));
  }

  // 3. Fast compound patterns (e.g. "Weeks 1-2", "Status: ...")
  if (text.startsWith("Weeks ") || text.startsWith("Week ")) {
    const wMap = { ta: "வாரங்கள்", hi: "सप्ताह", te: "వారాలు", ml: "ആഴ്ചകൾ", kn: "ವಾರಗಳು" };
    return rawText.replace(/Weeks?/g, wMap[targetLang] || "Weeks");
  }

  if (text.startsWith("Status: ")) {
    const statusVal = text.replace("Status: ", "").trim();
    const stMap = {
      ta: { "Excellent": "மிகச் சிறந்தது", "Good": "நன்று", "Average": "சராசரி", "Needs Improvement": "முன்னேற்றம் தேவை" },
      hi: { "Excellent": "उत्कृष्ट", "Good": "अच्छा", "Average": "औसत", "Needs Improvement": "सुधार की आवश्यकता" },
      te: { "Excellent": "అద్భుతం", "Good": "బాగుంది", "Average": "సగటు", "Needs Improvement": "మెరుగుపరచాలి" },
      ml: { "Excellent": "മികച്ചത്", "Good": "നല്ലത്", "Average": "ശരാശരി", "Needs Improvement": "മെച്ചപ്പെടുത്തേണ്ടതുണ്ട്" },
      kn: { "Excellent": "ಅತ್ಯುತ್ತಮ", "Good": "ಉತ್ತಮ", "Average": "ಸರಾಸರಿ", "Needs Improvement": "ಸುಧಾರಣೆಯ ಅಗತ್ಯವಿದೆ" }
    };
    const langSt = stMap[targetLang];
    const prefix = { ta: "நிலை:", hi: "स्थिति:", te: "స్థితి:", ml: "നില:", kn: "ಸ್ಥಿತಿ:" }[targetLang] || "Status:";
    if (langSt && langSt[statusVal]) {
      return `${prefix} ${langSt[statusVal]}`;
    }
  }

  return rawText;
}

// Precompute ultra-fast phrase maps across all languages
export const fastPhraseMaps = {
  ta: new Map(),
  hi: new Map(),
  te: new Map(),
  ml: new Map(),
  kn: new Map()
};

for (const [lang, dict] of Object.entries(PHRASE_DICTIONARY)) {
  const map = fastPhraseMaps[lang];
  if (map) {
    for (const [k, v] of Object.entries(dict)) {
      map.set(k, v);
      map.set(k.toLowerCase(), v);
    }
  }
}

/**
 * Recursively translates an element and its children
 */
function translateNode(node, targetLang) {
  if (!node) return;

  // Process text nodes
  if (node.nodeType === Node.TEXT_NODE) {
    const parentTag = node.parentElement ? node.parentElement.tagName : '';
    if (EXCLUDE_TAGS.has(parentTag)) return;

    // Cache original text node content
    if (!origTextMap.has(node)) {
      origTextMap.set(node, node.textContent);
    }

    const orig = origTextMap.get(node);

    if (targetLang === 'en') {
      if (node.textContent !== orig) {
        node.textContent = orig;
      }
    } else {
      const translated = translateText(orig, targetLang);
      if (translated && translated !== node.textContent) {
        node.textContent = translated;
      }
    }
    return;
  }

  // Process element nodes
  if (node.nodeType === Node.ELEMENT_NODE) {
    if (EXCLUDE_TAGS.has(node.tagName)) return;

    // Placeholder translation
    if (node.placeholder) {
      if (!origPlaceholderMap.has(node)) {
        origPlaceholderMap.set(node, node.placeholder);
      }
      const origPh = origPlaceholderMap.get(node);
      if (targetLang === 'en') {
        node.placeholder = origPh;
      } else {
        const transPh = translateText(origPh, targetLang);
        if (transPh) node.placeholder = transPh;
      }
    }

    // Title attribute translation
    if (node.title) {
      if (!origTitleMap.has(node)) {
        origTitleMap.set(node, node.title);
      }
      const origTit = origTitleMap.get(node);
      if (targetLang === 'en') {
        node.title = origTit;
      } else {
        const transTit = translateText(origTit, targetLang);
        if (transTit) node.title = transTit;
      }
    }

    // Recursively walk children
    let child = node.firstChild;
    while (child) {
      translateNode(child, targetLang);
      child = child.nextSibling;
    }
  }
}

let debounceTimer = null;
let currentActiveLang = 'en';

let hasTranslated = false;

/**
 * Scans the entire document and updates all text nodes in zero-lag O(1)
 */
export function runGlobalAutoTranslate(lang) {
  if (typeof document === 'undefined') return;
  if (!lang || (lang === 'en' && !hasTranslated)) return;
  currentActiveLang = lang;
  if (lang !== 'en') {
    hasTranslated = true;
  }
  translateNode(document.body, lang);
  if (lang === 'en') {
    hasTranslated = false;
  }
}

/**
 * Initializes DOM auto-translation. Only runs on explicit language switch.
 * Absolutely zero overhead during normal English usage.
 */
export function initAutoTranslate() {
  if (typeof window === 'undefined' || typeof document === 'undefined') return () => {};

  // Subscribe to langStore changes: only run sweep when user explicitly selects non-English or switches back
  const unsubscribe = langStore.subscribe(newLang => {
    if (!newLang) return;
    if (newLang === 'en' && !hasTranslated) return;
    currentActiveLang = newLang;
    if (debounceTimer) clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      runGlobalAutoTranslate(newLang);
    }, 50);
  });

  return () => {
    unsubscribe();
    if (debounceTimer) clearTimeout(debounceTimer);
  };
}
